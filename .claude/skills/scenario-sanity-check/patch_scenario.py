#!/usr/bin/env python3
"""Write a fast-timing copy of a scenario and its spec for the sanity check.

Usage: patch_scenario.py <spec.yaml.j2> <out-dir>

Copies the spec and the scenario it points at into <out-dir>, shrinking every
KEDA timing so scale-up and scale-down show up in about a minute. Triggers,
thresholds, min/max replicas, and scaleTargetRef are left alone, so the check
still exercises the scenario's own scaling signal. Prints the patched spec path
(last line) to pass as --spec, plus one line per change.

Run it with the llmdbenchmark venv's python (it has PyYAML).
"""
import re
import sys
from pathlib import Path

import yaml

POLL = 5          # KEDA pollingInterval, seconds
COOLDOWN = 10     # KEDA cooldownPeriod (scale-to-zero only), seconds
UP_PERIOD = 10    # HPA scaleUp policy periodSeconds
DOWN_WINDOW = 10  # HPA scaleDown stabilizationWindowSeconds
DOWN_PERIOD = 10  # HPA scaleDown policy periodSeconds


def setv(d, key, val, where, log):
    old = d.get(key)
    if old != val:
        d[key] = val
        log.append(f"{where}.{key}: {old} -> {val}")


def patch_scaled_object(so, log):
    w = so["name"]
    setv(so, "pollingInterval", POLL, w, log)
    if so.get("minReplicas", 1) == 0 or "cooldownPeriod" in so:
        setv(so, "cooldownPeriod", COOLDOWN, w, log)
    beh = so.setdefault("behavior", {})
    up = beh.setdefault("scaleUp", {})
    setv(up, "stabilizationWindowSeconds", 0, f"{w}.scaleUp", log)
    for p in up.setdefault("policies", [{"type": "Pods", "value": 1}]):
        setv(p, "periodSeconds", UP_PERIOD, f"{w}.scaleUp.policy", log)
    down = beh.setdefault("scaleDown", {})
    setv(down, "stabilizationWindowSeconds", DOWN_WINDOW, f"{w}.scaleDown", log)
    for p in down.setdefault("policies", [{"type": "Pods", "value": 1}]):
        setv(p, "periodSeconds", DOWN_PERIOD, f"{w}.scaleDown.policy", log)


def main(spec_arg, out_arg):
    root = Path.cwd()
    spec = Path(spec_arg)
    out = Path(out_arg)
    out.mkdir(parents=True, exist_ok=True)
    text = spec.read_text()
    m = re.search(r"scenario_file:\s*\n\s*path:\s*(.+?)\s*$", text, re.M)
    if not m:
        sys.exit(f"{spec}: no scenario_file.path found")
    # The spec path is `{{ base_dir }}/benchmark/config/scenarios/...`.
    rel = m.group(1).replace("{{ base_dir }}", "").lstrip("/")
    scenario = root / rel
    doc = yaml.safe_load(scenario.read_text())
    log = []

    def walk(node):
        if isinstance(node, dict):
            keda = node.get("keda")
            if isinstance(keda, dict):
                for so in keda.get("scaledObjects") or []:
                    patch_scaled_object(so, log)
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(doc)
    if not log:
        sys.exit(f"{scenario}: no keda.scaledObjects found; nothing to patch")
    new_scenario = out / f"sanity-{scenario.name}"
    new_scenario.write_text(
        "# Generated by scenario-sanity-check/patch_scenario.py. Do not commit.\n"
        + yaml.safe_dump(doc, sort_keys=False)
    )
    new_spec = out / f"sanity-{spec.name}"
    new_spec.write_text(
        text.replace(m.group(1), str(new_scenario.resolve()))
    )
    print("\n".join(log))
    print(new_spec.resolve())


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
